# Shared by the engine VM's install steps (apps/runner/deploy/install.sh,
# apps/codespace/deploy/install.sh). Sourced, not executed; runs as root.
#
# shellcheck shell=bash

ENGINE_PODMAN_URL=unix:///run/podman/podman.sock
ENGINE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# The rootful engine, always through its socket (root invariant 13).
pd() { podman --remote --url "$ENGINE_PODMAN_URL" "$@"; }

# engine_lock <seconds>: one deploy at a time on the VM, the lock the frozen
# staging dispatcher takes too (its LOCK). Held on descriptor 9, which an
# exec and the children keep; a no-op when the caller already holds it
# (QUIZ_DEPLOY_LOCKED). Returns 1 when not obtained within <seconds>.
ENGINE_LOCK=/run/quiz-engine-deploy.lock
engine_lock() {
	[ -z "${QUIZ_DEPLOY_LOCKED:-}" ] || return 0
	exec 9>"$ENGINE_LOCK"
	flock -w "$1" 9 || return 1
	export QUIZ_DEPLOY_LOCKED=1
}

# pull_retag <repository> <sha> <local tag>: pulls the CI's image of the sha
# and gives it the tag the quadlet runs (Pull=never: never the registry's
# moving tag). With QUIZ_DEPLOY_DIGEST (set by deploy.sh from the CI's
# request, audit M8) the pull is by that digest, the bytes the CI built, and
# the image ID the pull prints is tagged with the sha locally; without it,
# the pull is by the sha tag.
pull_retag() {
	local id
	if [ -n "${QUIZ_DEPLOY_DIGEST:-}" ]; then
		id=$(pd pull -q "$1@$QUIZ_DEPLOY_DIGEST")
		pd tag "$id" "$1:$2"
	else
		pd pull "$1:$2"
	fi
	pd tag "$1:$2" "$1:$3"
}

# What the host itself holds outside both slices (Caddy, Podman, conmon,
# systemd, sshd, sysstat), in MiB: the ~0.3 GB of the 2026-10-08 sizing,
# 256 so that the rounding below keeps 2048 for every "4 GB" VM.
ENGINE_HOST_RESERVE_MIB=256
# The workspace slice's MemoryMax never goes below this, the value of the
# 3.8 GB VM since 2026-10-08: a smaller computation (a smaller VM, a larger
# runner MemoryLow) never shrinks the slice; install_slices says so.
CODESPACE_MEMORY_FLOOR_MIB=2048

# codespace_memory_limits <MemTotal kB> <runner MemoryLow MiB>: prints
# "<MemoryHigh MiB> <MemoryMax MiB>" for codespace.slice. What the VM's RAM
# leaves once the runner's protected memory and the host's reserve are
# taken, rounded to the NEAREST 256 MiB, at least CODESPACE_MEMORY_FLOOR_MIB;
# MemoryHigh is 7/8 of it (1792 at the floor). Swap is not counted: MemTotal
# is RAM only.
codespace_memory_limits() {
	local total_mib=$(($1 / 1024)) max
	max=$(((total_mib - $2 - ENGINE_HOST_RESERVE_MIB + 128) / 256 * 256))
	[ "$max" -ge "$CODESPACE_MEMORY_FLOOR_MIB" ] || max=$CODESPACE_MEMORY_FLOOR_MIB
	echo "$((max - max / 8)) $max"
}

# install_slices: the two slices of the VM (M6-05), quiz-runner.slice and
# codespace.slice, into /etc/systemd/system/, and codespace.slice's memory
# lines as a drop-in computed from this VM's RAM (codespace_memory_limits;
# the runner's slice is fixed, its MemoryLow read from its file). Everything
# is read and computed first, the drop-in replaced atomically (a temporary
# file in its directory, then mv), the slice files installed last: a failed
# read writes nothing. The caller's daemon-reload applies a changed weight
# or limit to the RUNNING slice, drop-in included (checked on systemd 259:
# memory.max follows at daemon-reload, nothing restarts). After a resize,
# run it again (RUNBOOK.md, Capacity). A slice a unit names before its file
# exists is created empty by systemd, so the order of the deploys does not
# matter. SYSTEMD_UNIT_DIR and MEMINFO serve the test (slices.test.sh).
install_slices() {
	local dir="${SYSTEMD_UNIT_DIR:-/etc/systemd/system}" kb low limits tmp
	kb=$(awk '$1 == "MemTotal:" && $2 ~ /^[0-9]+$/ { print $2 }' "${MEMINFO:-/proc/meminfo}" 2>/dev/null)
	low=$(sed -n 's/^MemoryLow=\([0-9][0-9]*\)M$/\1/p' "$ENGINE_DIR/quiz-runner.slice" 2>/dev/null)
	if [ -z "$kb" ] || [ -z "$low" ]; then
		echo "deploy: no MemTotal, or quiz-runner.slice's MemoryLow is not in MiB: the slices are left as they are" >&2
		return 1
	fi
	limits=$(codespace_memory_limits "$kb" "$low")
	if [ "$(((kb / 1024 - low - ENGINE_HOST_RESERVE_MIB + 128) / 256 * 256))" -lt "$CODESPACE_MEMORY_FLOOR_MIB" ]; then
		echo "deploy: warning: $((kb / 1024)) MiB of RAM: codespace.slice keeps its floor, ${CODESPACE_MEMORY_FLOOR_MIB}M, part of it inside the runner's MemoryLow" >&2
	fi
	install -d -m 0755 "$dir/codespace.slice.d" || return 1
	tmp=$(mktemp "$dir/codespace.slice.d/.50-memory.conf.XXXXXX") || return 1
	if ! printf '%s\n' \
		"# Generated by install_slices (infra/engine/lib.sh) from MemTotal ${kb} kB" \
		"# and quiz-runner.slice's MemoryLow ${low}M. Do not edit: rewritten at every deploy." \
		"[Slice]" \
		"MemoryHigh=${limits% *}M" \
		"MemoryMax=${limits#* }M" > "$tmp" ||
		! chmod 0644 "$tmp" || ! mv -f "$tmp" "$dir/codespace.slice.d/50-memory.conf"; then
		rm -f "$tmp"
		return 1
	fi
	install -m 0644 "$ENGINE_DIR/quiz-runner.slice" "$ENGINE_DIR/codespace.slice" "$dir/"
}

# warn_manual_drift: a deploy never touches the host firewall, nor the frozen
# staging dispatcher; it only says when the checkout's host.nft or
# staging-dispatch.sh differs from the installed copy (or none is installed
# yet). Installing stays manual (nft-apply.sh, deployment.md §3; the
# dispatcher, deployment.md §4).
warn_manual_drift() {
	cmp -s "$ENGINE_DIR/host.nft" /etc/quiz-engine/host.nft \
		|| echo "deploy: warning: infra/engine/host.nft differs from the applied copy: run nft-apply.sh (deployment.md §3)" >&2
	cmp -s "$ENGINE_DIR/staging-dispatch.sh" /usr/local/libexec/quiz-engine/staging-dispatch.sh \
		|| echo "deploy: warning: infra/engine/staging-dispatch.sh differs from the installed copy: read the difference, then install it by hand (deployment.md §4, The frozen staging dispatcher)" >&2
}

# drop_old_sha_tags <repository> <sha to keep>: untags every other 40-hex
# tag of the repository, then deletes the repository's images no tag names
# any more. Never a global prune: other services and sessions share this
# engine.
#
# Untagging alone deletes nothing since the pull is by digest (pull_retag):
# the image keeps its `<repository>@sha256:…` name, shows as `<none>`, is
# not dangling, and `podman image prune` (without -a) keeps it. Hence the
# second loop, by image ID, on the IDs of the repository's `<none>` rows that
# have no tag left at all (RepoTags empty: `podman rmi <id>` deletes an image
# named by a single tag, so the check is not optional). An image that keeps
# any tag (:latest, :prod, :staging, the current sha), of any repository,
# stays: the prod and staging portals share this store and protect each
# other's image by their tag. Never `rmi -f`, which removes the containers
# using the image: an image in use refuses the rmi and stays.
drop_old_sha_tags() {
	local old id
	for old in $(pd images --format '{{.Tag}}' --filter "reference=$1" \
		| grep -E '^[0-9a-f]{40}$' | grep -vx "$2" | sort -u || true); do
		pd rmi "$1:$old" >/dev/null 2>&1 || true
	done
	for id in $(pd images --no-trunc --format '{{.ID}} {{.Tag}}' --filter "reference=$1" \
		| awk '$2 == "<none>" { print $1 }' | sort -u || true); do
		[ "$(pd image inspect --format '{{len .RepoTags}}' "$id" 2>/dev/null)" = 0 ] || continue
		pd rmi "$id" >/dev/null 2>&1 || true
	done
}

# The VM's Caddy (its unit reloads with `caddy reload --force`): a component
# installs its sites with caddy_site, validates, then calls caddy_apply ONCE
# where it used to run `systemctl reload caddy`; a reload can stay pending,
# so none is made that is not needed (apps/codespace/deploy/RUNBOOK.md,
# Caddy reloads). The variables serve the test (caddy.test.sh). Every
# cs_instance sources this file again (through infra/net/common.sh): each
# one keeps the value it has.
CADDY_CONFIG="${CADDY_CONFIG:-/etc/caddy/Caddyfile}"
CADDY_ADMIN="${CADDY_ADMIN:-http://127.0.0.1:2019}"
CADDY_RELOAD_TIMEOUT="${CADDY_RELOAD_TIMEOUT:-60}"
CADDY_CHANGED="${CADDY_CHANGED:-}"

# caddy_site <rendered fragment> <installed path>: installs the fragment
# (0644) only when its content differs from the installed copy, says so, and
# records it in CADDY_CHANGED.
caddy_site() {
	cmp -s "$1" "$2" && return 0
	install -m 0644 "$1" "$2" || return 1
	CADDY_CHANGED=1
	echo "deploy: caddy: $2 changed"
}

# caddy_state: 0 when the running config (the admin API's /config/) is what
# CADDY_CONFIG adapts to, compared as parsed JSON (python3, already a
# dependency of the network test: no jq); 2 when the admin API does not
# answer within 10 s (a reload still pending); 1 otherwise, a comparison
# that cannot be made included.
caddy_state() {
	local running wanted rc=0
	running=$(curl -fsS -m 10 "$CADDY_ADMIN/config/" 2>/dev/null) || rc=$?
	[ "$rc" != 28 ] || return 2
	[ "$rc" = 0 ] || return 1
	wanted=$(caddy adapt --config "$CADDY_CONFIG" --adapter caddyfile 2>/dev/null) || return 1
	printf '%s\0%s' "$running" "$wanted" | python3 -I -c '
import json, sys
running, wanted = sys.stdin.buffer.read().split(b"\0")
sys.exit(0 if json.loads(running) == json.loads(wanted) else 1)' 2>/dev/null
}

# caddy_apply: reloads Caddy at most once, and only when the running config
# is not the one the files give (a fragment changed, or an earlier reload
# did not take); the caller has validated the files. The reload is bounded
# by CADDY_RELOAD_TIMEOUT: `timeout` stops systemctl, the client, never
# systemd's job, which ends by the unit's own rules. Then it checks what
# Caddy runs. It fails only when Caddy runs the old config, or when an
# earlier reload is still pending and a site changed (no second reload is
# queued behind it). Never restarts Caddy: that would cut every live session.
caddy_apply() {
	local state=0 rc=0
	caddy_state || state=$?
	case "$state" in
		0)
			echo "deploy: caddy: runs this configuration, no reload"
			return 0
			;;
		2)
			if [ -z "$CADDY_CHANGED" ]; then
				echo "deploy: warning: an earlier Caddy reload is still pending; no site changed, no reload" >&2
				return 0
			fi
			echo "deploy: an earlier Caddy reload is still pending: this deploy's site change is not live; re-run the deploy later (apps/codespace/deploy/RUNBOOK.md, Caddy reloads)" >&2
			return 1
			;;
	esac
	timeout "$CADDY_RELOAD_TIMEOUT" systemctl reload caddy || rc=$?
	state=0
	caddy_state || state=$?
	case "$rc:$state" in
		0:*) echo "deploy: caddy reloaded" ;;
		*:0) echo "deploy: warning: systemctl reload caddy returned $rc, but Caddy runs the new configuration" >&2 ;;
		*:2) echo "deploy: warning: Caddy reload still pending: the new configuration serves; further reloads will wait until it completes" >&2 ;;
		*)
			echo "deploy: systemctl reload caddy failed (exit $rc) and Caddy does not run the new configuration: sudo journalctl -u caddy" >&2
			return 1
			;;
	esac
}
